export function searchArticles(query: string): Article[] {
  const normalizedQuery = query.trim().toLowerCase();
  if (!normalizedQuery) return [];

  return demoArticles
    .filter((a) => {
      const titleMatch = a.title.toLowerCase().includes(normalizedQuery);
      const summaryMatch = a.summary.toLowerCase().includes(normalizedQuery);
      const englishMatch = a.englishTitle?.toLowerCase().includes(normalizedQuery);
      const categoryMatch =
        a.categoryName.toLowerCase().includes(normalizedQuery) ||
        a.categorySlug.toLowerCase().includes(normalizedQuery);
      const tagMatch = a.tags.some((t) => t.toLowerCase().includes(normalizedQuery));
      const authorMatch =
        a.author.name.toLowerCase().includes(normalizedQuery) ||
        a.author.englishName?.toLowerCase().includes(normalizedQuery);
      const bodyMatch = a.body.some((b) =>
        "text" in b && b.text ? b.text.toLowerCase().includes(normalizedQuery) : false
      );

      return (
        titleMatch ||
        summaryMatch ||
        englishMatch ||
        categoryMatch ||
        tagMatch ||
        authorMatch ||
        bodyMatch
      );
    })
    .sort((a, b) => new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime());
}
